#!/usr/bin/env node
// The coversheet for a charge with no document.
//
// The whole risk in this feature is one sentence: a generated page that reads
// like a vendor's invoice, filed beside real ones, becomes a made-up document
// presented as evidence. Nobody sets out to do that — it happens because the page
// looks the part and nothing on it says otherwise.
//
// So these checks are almost entirely about what the page SAYS ABOUT ITSELF, and
// they are worth more than the layout ones.
//
//   node scripts/checkChargeSheet.js

const fs = require('fs');
const path = require('path');

const src = fs.readFileSync(path.join(__dirname, '..', 'server.js'), 'utf8');
const at = src.indexOf("app.get('/api/renovations/charge-sheet'");
if (at < 0) { console.error('✗ the charge-sheet route is gone'); process.exit(1); }
const route = src.slice(at, src.indexOf("app.get('/api/renovations/backup/file'", at));

let fails = 0, checks = 0;
const check = (name, ok, detail) => {
  checks++;
  if (ok) { console.log(`  ✓ ${name}`); return; }
  fails++;
  console.log(`  ✗ ${name}${detail ? `\n      ${detail}` : ''}`);
};

console.log('\nIt says what it is, everywhere someone might look');
check('the title calls it a summary, not an invoice',
  /<title>Charge summary/.test(route) && /<h1>Charge summary<\/h1>/.test(route));
check('a banner states plainly that it is not an invoice',
  /This is not an invoice/.test(route));
check('...and that it must not be filed as a vendor document',
  /must not be filed as one/.test(route));
check('the footer repeats it, because a printed page loses its first screen',
  /Not a vendor invoice/.test(route));
check('it names itself as generated by this site, with a timestamp',
  /Generated by the Cedar Ridge Management management site/.test(route)
  && /toISOString\(\)/.test(route));

console.log('\nIt never dresses up as a vendor document');
const BAD = [/\bINVOICE\s*#/i, /\bBill\s+To\b/i, /\bRemit\s+To\b/i, /\bAmount\s+Due\b/i,
  /\bTerms\b\s*:/i, /\bPay\s+by\b/i];
const dressed = BAD.filter(re => re.test(route));
check('no invoice furniture — no "Bill To", "Remit To", "Amount Due", "Invoice #"',
  !dressed.length, dressed.map(String).join(', '));
check('it does not reproduce a vendor logo or letterhead',
  !/<img/i.test(route));

console.log('\nIt is honest about the charge');
check('every field comes from the snapshot or the backup lookup, none invented',
  /charge\.propertyName/.test(route) && /charge\.accountRef/.test(route)
  && /manualLookup/.test(route));
check('when a document DOES exist it says so rather than pretending to replace it',
  /Documents in Rent Manager/.test(route));
check('it carries the reason no document was found',
  /Why there is no document/.test(route) && /unavailable/.test(route));
check('it keeps the by-hand lookup path, so the sheet is a pointer not a dead end',
  /To find it by hand in Rent Manager/.test(route));

console.log('\nIt does not carry a conclusion that has been overturned');
// The sheet quotes backupFor's own explanation, so a stale explanation is printed
// on a document somebody files. This one told readers to email Rent Manager
// support about a document store, a day after a bill embed produced a 288 KB
// invoice.
const docs = fs.readFileSync(path.join(__dirname, '..', 'services', 'rmDocuments.js'), 'utf8');
check('no message still claims this API exposes no document store',
  !/exposes no document store/.test(docs),
  'documents are reachable through the bill; the store never existed and that is not news');
check('no message still tells the reader to email Rent Manager support',
  !/send that to Rent Manager support/.test(docs),
  'nothing is blocked at their end — that instruction sends someone on a wrong errand');
check('a bill with nothing attached says the document was never uploaded',
  /never uploaded against it/.test(docs));

console.log('\nIt cannot be pointed at anything but a real charge');
check('the charge must exist in the current snapshot',
  /charges \|\| \[\]\)\.find\(c => c\.id === chargeId\)/.test(route)
  && /404/.test(route));
check('no id, no page', /Need \?id=<charge>/.test(route));
check('user-supplied values are escaped into the HTML',
  /replace\(\/&\/g, '&amp;'\)/.test(route) && /esc\(chargeId\)/.test(route));

console.log('\nThe tab offers it only where it belongs');
const html = fs.readFileSync(path.join(__dirname, '..', 'public', 'index.html'), 'utf8');
const btn = html.indexOf('charge-sheet?id=');
check('the control exists', btn > 0);
const around = html.slice(Math.max(0, btn - 900), btn + 300);
// It moved off the row and into the backup panel (2026-09-22) — it was a third
// button competing with the two real actions, and it belongs beside the
// explanation of why there is no document. The RULE is unchanged and is what
// this check is really about: never offered beside a real invoice.
check('...only where the charge has NO document, so nobody files the summary instead of the invoice',
  /!\(bk\.attachments && bk\.attachments\.length\)/.test(around),
  'offering it beside a real invoice is the wrong way round');
check('...opening in a new tab rather than replacing the board', /target="_blank"/.test(around));
// The row is the thing people scan thousands of; it carries the two actions
// anybody chooses between and nothing else.
const rows = /function renoChargeRows\(charges\) \{[\s\S]*?\n  \}/.exec(html);
check('the charge row does not carry it any more', rows && !/charge-sheet/.test(rows[0]),
  'three competing controls per row is what this cleanup removed');
check('...and still carries exactly the two that matter',
  rows && /charge-packet\?id=/.test(rows[0]) && /renoLoadBackup/.test(rows[0]),
  'open it here, or take the file away');

console.log(`\n${fails === 0 ? '✓' : '✗'} ${checks - fails}/${checks} checks passed`);
process.exit(fails === 0 ? 0 : 1);
